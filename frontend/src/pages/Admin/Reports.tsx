import { motion } from "framer-motion";
import { toast } from "sonner";
import { Download, FileBarChart, Sparkles } from "lucide-react";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/cards/Card";
import { DataTable } from "@/components/tables/Table";
import { InlineLoader } from "@/components/loaders/Loader";
import { Button } from "@/components/ui/Button";
import { useGeneratedReportsQuery, useReportDefinitionsQuery } from "@/hooks/useAdminQueries";
import { useGenerateReportMutation } from "@/hooks/useAdminMutations";
import type { GeneratedReport } from "@/types/admin";
import type { TableColumn } from "@/types";

const categoryStyles: Record<string, string> = {
  Placement: "bg-emerald-500/10 text-emerald-600 dark:text-emerald-400",
  Growth: "bg-blue-500/10 text-blue-600 dark:text-blue-400",
  Engagement: "bg-purple-500/10 text-purple-600 dark:text-purple-400",
  Financial: "bg-amber-500/10 text-amber-600 dark:text-amber-400",
};

export function Reports() {
  const { data: definitions, isLoading: definitionsLoading } = useReportDefinitionsQuery();
  const { data: history, isLoading: historyLoading } = useGeneratedReportsQuery();
  const generateMutation = useGenerateReportMutation();

  const handleDownload = async (report: GeneratedReport) => {
    const { jsPDF } = await import("jspdf");
    const doc = new jsPDF();
    doc.setFontSize(14);
    doc.text(report.title, 15, 20);
    doc.setFontSize(10);
    doc.text(`Generated on ${report.generatedOn} by ${report.generatedBy}`, 15, 28);
    doc.text(
      "This is a placeholder export. Once connected to the backend, this report will include full platform data tables and charts.",
      15,
      40,
      { maxWidth: 180 }
    );
    doc.save(`${report.title.replace(/\s+/g, "_")}.pdf`);
    toast.success("Report downloaded");
  };

  const historyColumns: TableColumn<GeneratedReport>[] = [
    { key: "title", header: "Report" },
    { key: "generatedOn", header: "Generated On" },
    { key: "generatedBy", header: "Generated By" },
    {
      key: "actions",
      header: "",
      render: (row) => (
        <Button size="sm" variant="outline" onClick={() => handleDownload(row)}>
          <Download className="h-3.5 w-3.5" /> Download
        </Button>
      ),
    },
  ];

  return (
    <div className="space-y-6">
      <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }}>
        <h1 className="text-2xl font-semibold text-foreground">Reports</h1>
        <p className="text-sm text-muted-foreground">
          Generate and download platform-wide reports for stakeholders.
        </p>
      </motion.div>

      <Card>
        <CardHeader className="flex-row items-center gap-2 space-y-0">
          <Sparkles className="h-4 w-4 text-primary" />
          <CardTitle>Generate a Report</CardTitle>
        </CardHeader>
        <CardContent>
          {definitionsLoading ? (
            <InlineLoader />
          ) : (
            <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
              {definitions?.map((def) => (
                <div key={def.id} className="flex flex-col justify-between rounded-md border border-border p-4">
                  <div>
                    <span
                      className={`rounded-full px-2 py-0.5 text-xs font-medium ${categoryStyles[def.category]}`}
                    >
                      {def.category}
                    </span>
                    <p className="mt-2 text-sm font-medium text-foreground">{def.title}</p>
                    <p className="mt-1 text-xs text-muted-foreground">{def.description}</p>
                  </div>
                  <Button
                    size="sm"
                    className="mt-3 w-full"
                    isLoading={generateMutation.isPending}
                    onClick={() => generateMutation.mutate(def.id)}
                  >
                    Generate
                  </Button>
                </div>
              ))}
            </div>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader className="flex-row items-center gap-2 space-y-0">
          <FileBarChart className="h-4 w-4 text-primary" />
          <CardTitle>Report History</CardTitle>
        </CardHeader>
        <CardContent>
          {historyLoading ? (
            <InlineLoader />
          ) : (
            <DataTable columns={historyColumns} data={history ?? []} getRowKey={(row) => row.id} />
          )}
        </CardContent>
      </Card>
    </div>
  );
}

export default Reports;
